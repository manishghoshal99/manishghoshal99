#!/usr/bin/env python3
"""Bake the two pixel fonts into tools/glyphs.py, a plain-data module.

The GitHub Action that redraws the pond imports glyphs.py, so it needs no
font files or third-party packages. Run this only when the fonts change:

    python tools/bake_glyphs.py      (needs Pillow)

Sources, both in tools/fontsrc/:
- Pixel Operator by HarvettFox96, CC0 / SIL OFL, as the bitmap atlas shipped
  with MG Quest (pixelop.png and pixelop.xml).
- Press Start 2P by CodeMan38, SIL OFL 1.1 (PressStart2P-Regular.ttf), drawn
  at its native 8 px grid. The licence is in OFL-PressStart2P.txt.
"""

from __future__ import annotations

import pathlib
import pprint
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).parent
SRC = HERE / "fontsrc"
CHARS = [chr(c) for c in range(32, 127)]


def rows_of(img: Image.Image) -> list[str]:
    """Encode a 1-bit glyph image as one hex string per row (bit set = ink)."""
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        bits = 0
        for x in range(w):
            if px[x, y]:
                bits |= 1 << x
        out.append(format(bits, "x"))
    return out


def bake_operator() -> dict:
    """Pixel Operator: crop each glyph from the BMFont atlas (black ink on white)."""
    atlas = Image.open(SRC / "pixelop.png").convert("L")
    root = ET.parse(SRC / "pixelop.xml").getroot()
    common = root.find("common").attrib
    glyphs = {}
    for c in root.find("chars"):
        a = {k: int(v) for k, v in c.attrib.items() if k != "chnl"}
        ch = chr(a["id"])
        box = atlas.crop((a["x"], a["y"], a["x"] + a["width"], a["y"] + a["height"]))
        ink = box.point(lambda v: 255 if v < 128 else 0).convert("1")
        rows = rows_of(ink) if ch != " " else []
        glyphs[ch] = (a["xadvance"], a["xoffset"], a["yoffset"], a["width"] if rows else 0, rows)
    return {"line": int(common["lineHeight"]), "base": int(common["base"]), "glyphs": glyphs}


def bake_press_start() -> dict:
    """Press Start 2P: draw every glyph unsmoothed at 8 px, its design grid."""
    font = ImageFont.truetype(str(SRC / "PressStart2P-Regular.ttf"), 8)
    glyphs = {}
    for ch in CHARS:
        img = Image.new("1", (16, 16), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"
        draw.text((0, 0), ch, font=font, fill=1)
        bbox = img.getbbox()
        advance = round(font.getlength(ch))
        if not bbox:
            glyphs[ch] = (advance, 0, 0, 0, [])
            continue
        x0, y0, x1, y1 = bbox
        glyphs[ch] = (advance, x0, y0, x1 - x0, rows_of(img.crop(bbox)))
    return {"line": 8, "base": 7, "glyphs": glyphs}


def main() -> None:
    data = {"operator": bake_operator(), "press": bake_press_start()}
    missing = [ch for ch in CHARS if ch not in data["operator"]["glyphs"]]
    assert not missing, f"Pixel Operator atlas lacks {missing}"
    header = (
        '"""Generated by tools/bake_glyphs.py. Do not edit by hand.\n\n'
        "Each glyph is (advance, x offset, y offset, width, rows), rows as hex\n"
        "bitmasks with bit 0 at the left. Fonts: Pixel Operator (CC0 / OFL) and\n"
        'Press Start 2P (SIL OFL 1.1, see fontsrc/OFL-PressStart2P.txt)."""\n\n'
    )
    body = "FONTS = " + pprint.pformat(data, width=100, sort_dicts=True) + "\n"
    (HERE / "glyphs.py").write_text(header + body, encoding="utf-8")
    print(f"wrote tools/glyphs.py ({len(body) / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
